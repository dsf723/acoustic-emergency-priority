def columns(art):
    rows = art.split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), art
    return [sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5)]


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sw", "src", "font5x7.h")
    lines = [
        "/* 5x7 点阵字库，ASCII 32~127，每字 5 列，bit0 为最上一行。",
        " * 由 tools/gen_font.py 生成，请勿手工修改。0x7F 为度数符号。 */",
        "#ifndef FONT5X7_H",
        "#define FONT5X7_H",
        "",
        "#include <stdint.h>",
        "",
        "static const uint8_t font5x7[96][5] = {",
    ]
    for code in range(32, 128):
        ch = chr(code)
        art = GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or GLYPHS[" "]
        cols = ", ".join(f"0x{c:02X}" for c in columns(art))
        name = "deg" if code == 127 else ("\\\\" if ch == "\\" else ch)
        lines.append(f"    {{ {cols} }},  /* 0x{code:02X} {name} */")
    lines += ["};", "", "#endif", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as fp:
        fp.write("\n".join(lines))
    print("written", os.path.normpath(out))


if __name__ == "__main__":
    main()
